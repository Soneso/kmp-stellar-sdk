# frozen_string_literal: true

require 'minitest/autorun'
require 'fileutils'
require 'tmpdir'
require 'xdrgen'
require_relative '../lib/xdrgen/generators/kotlin_json_tests'

# The XDR-JSON test emitter, exercised over the same fixtures the Kotlin generator uses.
#
# What is asserted here is the shape of the emitted suite: that every type gets a round trip,
# every enum member and every union arm gets its own assertion, and that a sampled value is
# built without randomness and terminates. Whether the suite passes is the SDK build's answer,
# not this file's.
class JsonTestsEmitterTest < Minitest::Test
  FIXTURE_DIR = File.expand_path('fixtures', __dir__)
  SDK_TEST_DIR = File.expand_path(
    '../../../stellar-sdk/src/commonTest/kotlin/com/soneso/stellar/sdk/unitTests/xdr/json',
    __dir__
  )

  @@output_dir = nil
  @@generated = false

  def setup
    unless @@generated
      @@output_dir = Dir.mktmpdir('xdr_json_tests_')
      fixtures = Dir.glob(File.join(FIXTURE_DIR, '*.x')).sort
      raise "No .x fixtures found in #{FIXTURE_DIR}" if fixtures.empty?

      Xdrgen::Compilation.new(
        fixtures,
        output_dir: "#{@@output_dir}/",
        generator: Xdrgen::Generators::KotlinJsonTests,
        namespace: 'com.soneso.stellar.sdk.xdr',
        options: {}
      ).compile

      @@generated = true
    end
    @output_dir = @@output_dir
  end

  Minitest.after_run { FileUtils.rm_rf(@@output_dir) if @@output_dir }

  # -- Emitted layout ---------------------------------------------------------

  # One file per .x source that declares a type, plus the shared sample values. A source
  # declaring only constants contributes no type and therefore no file.
  def test_output_is_grouped_by_source_file
    emitted = Dir.glob(File.join(@output_dir, '*.kt')).map { |f| File.basename(f) }.sort
    assert_equal %w[
      XdrJsonSampleValues.kt
      XdrJsonTestEnumTest.kt
      XdrJsonTestStructTest.kt
      XdrJsonTestTypedefTest.kt
      XdrJsonTestUnionTest.kt
    ], emitted
  end

  def test_every_emitted_file_carries_the_generated_marker_and_test_package
    Dir.glob(File.join(@output_dir, '*.kt')).each do |file|
      content = File.read(file)
      assert content.start_with?('// Automatically generated by xdrgen'),
        "#{File.basename(file)} does not open with the generated marker"
      assert_includes content, 'package com.soneso.stellar.sdk.unitTests.xdr.json',
        "#{File.basename(file)} declares the wrong package"
    end
  end

  # -- Coverage of the type set -----------------------------------------------

  def test_every_type_gets_a_round_trip_or_member_assertion
    body = combined_output
    %w[
      simpleStructXdrRoundTripsThroughItsJsonTree
      nestedStructXdrRoundTripsThroughItsJsonTree
      resultXdrRoundTripsThroughItsJsonTree
      int64XdrRoundTripsThroughItsJsonTree
      hashXdrRoundTripsThroughItsJsonTree
    ].each { |test| assert_includes body, "fun #{test}()" }
  end

  def test_every_enum_member_is_asserted_on_its_wire_name_and_number
    body = combined_output
    assert_includes body, 'fun colorXdrRendersRedAsRed() {'
    assert_includes body, 'val member = ColorXdr.RED'
    assert_includes body, 'assertEquals(0, member.value)'
    assert_includes body, 'assertEquals(JsonPrimitive("red"), member.toXdrJsonElement())'
    assert_includes body, 'assertEquals(member, ColorXdr.fromXdrJson("\"red\""))'
    assert_includes body, 'fun statusCodeXdrRendersStatusNotFoundAsNotFound() {'
  end

  def test_every_union_arm_is_asserted_on_its_key
    body = combined_output
    assert_includes body, 'assertEquals(listOf("error"), jsonKeys(tree))'
    assert_includes body, 'assertEquals(JsonPrimitive("ok"), tree)'
    assert_includes body, 'fun multiCaseUnionXdrRendersTextValue1ArmAsV1() {'
    assert_includes body, 'fun multiCaseUnionXdrRendersTextValue2ArmAsV2() {'
  end

  # A union arm reachable only through the default branch is constructed at a discriminant no
  # case names, which is the only way that branch is exercised.
  def test_the_default_arm_is_built_at_an_unclaimed_discriminant
    body = combined_output
    assert_includes body, 'fun multiCaseUnionXdrRendersRawValueDefaultArmAsV3() {'
    assert_includes body, 'internal fun sampleMultiCaseUnionXdrRawValueDefaultArm(seed: Int, depth: Int)'
  end

  def test_every_type_gets_a_rejection_assertion
    body = combined_output
    assert_includes body, 'fun simpleStructXdrRejectsInputThatIsNotItsObject() {'
    assert_includes body, 'fun resultXdrRejectsAnArmItDoesNotDeclare() {'
    assert_includes body, 'fun colorXdrRejectsAMemberItDoesNotDeclare() {'
    assert_includes body, 'fun hashXdrRejectsInputOfTheWrongShape() {'
  end

  # -- Sampling ---------------------------------------------------------------

  def test_sampled_values_are_a_pure_function_of_a_seed
    body = combined_output
    refute_includes body, 'Random', 'a sampled value must not depend on a random source'
    assert_includes File.read(File.join(@output_dir, 'XdrJsonSampleValues.kt')),
      'internal fun sampleInt(seed: Int): Int'
  end

  def test_a_variable_length_member_is_truncated_at_the_depth_limit
    body = combined_output
    assert_includes body, 'if (depth < SAMPLE_DEPTH)'
    assert_includes File.read(File.join(@output_dir, 'XdrJsonSampleValues.kt')),
      'internal const val SAMPLE_DEPTH: Int = 3'
  end

  # An .x set whose types can only be built by nesting one within itself has no finite sample,
  # and the emitter has to say so rather than emit a builder that exhausts the stack.
  def test_a_type_with_no_finite_value_is_rejected
    Dir.mktmpdir('xdr_json_infinite_') do |source_dir|
      File.write(File.join(source_dir, 'infinite.x'), <<~XDR)
        namespace stellar {
          struct Loop {
            Loop inner;
          };
        }
      XDR

      error = assert_raises(RuntimeError) do
        Dir.mktmpdir('xdr_json_infinite_out_') do |output_dir|
          Xdrgen::Compilation.new(
            [File.join(source_dir, 'infinite.x')],
            output_dir: "#{output_dir}/",
            generator: Xdrgen::Generators::KotlinJsonTests,
            namespace: 'com.soneso.stellar.sdk.xdr',
            options: {}
          ).compile
        end
      end
      assert_includes error.message, 'no finite sample exists for LoopXdr'
    end
  end

  # -- Committed output -------------------------------------------------------

  # The suite that ships is the one in the SDK's test sources; the fixtures exercise only the
  # constructs they happen to declare.
  def test_the_committed_suite_covers_every_generated_type
    emitted = Dir.glob(File.join(SDK_TEST_DIR, '*.kt'))
                 .select { |file| File.read(file).start_with?('// Automatically generated by xdrgen') }
    assert emitted.length >= 10, "expected the committed XDR-JSON suite, found #{emitted.length} files"

    body = emitted.map { |file| File.read(file) }.join("\n")
    generated_types = Dir.glob(File.expand_path(
      '../../../stellar-sdk/src/commonMain/kotlin/com/soneso/stellar/sdk/xdr/*.kt', __dir__
    )).select { |file| File.read(file).include?('fun toXdrJsonElement()') }
      .map { |file| File.basename(file, '.kt') }

    assert generated_types.length > 400,
      "expected the generated SDK types, found #{generated_types.length}"

    missing = generated_types.reject do |type|
      body.include?("sample#{type}(") || body.include?("val member = #{type}.")
    end
    assert missing.empty?, "no sampled value is emitted for: #{missing.join(', ')}"
  end

  private

  def combined_output
    @combined_output ||= Dir.glob(File.join(@output_dir, '*.kt')).sort
                            .map { |file| File.read(file) }.join("\n")
  end
end
