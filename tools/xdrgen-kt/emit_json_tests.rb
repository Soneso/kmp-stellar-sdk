#!/usr/bin/env ruby
# frozen_string_literal: true

require 'bundler/setup'
require 'fileutils'
require 'json'
require 'xdrgen'
require_relative 'lib/xdrgen/generators/kotlin_json_tests'

# Emits the XDR-JSON (SEP-0051) test suite for the generated XDR types.
#
# Reads the same .x files and applies the same exclusions as generate.rb, so the suite covers
# exactly the types the SDK generates. Output is grouped by .x source file.

input_files = ARGV
if input_files.empty?
  default_dir = File.expand_path('xdr', __dir__)
  input_files = Dir.glob(File.join(default_dir, '*.x')).sort
  if input_files.empty?
    puts "No .x files found in #{default_dir}."
    puts 'Run ./download-xdr.sh first, or pass file paths explicitly.'
    exit 1
  end
  puts "Using .x files from #{default_dir}"
end

# The same three files generate.rb drops: their types are Core-internal and the SDK does not
# generate them, so there is nothing to test.
excluded_files = %w[
  Stellar-exporter.x
  Stellar-internal.x
  Stellar-overlay.x
].freeze

filtered_files = input_files.reject { |file| excluded_files.include?(File.basename(file)) }

if filtered_files.empty?
  puts 'Error: All input files were excluded. No files to process.'
  exit 1
end

output_dir = File.expand_path(
  '../../stellar-sdk/src/commonTest/kotlin/com/soneso/stellar/sdk/unitTests/xdr/json',
  __dir__
)
FileUtils.mkdir_p(output_dir)

# --- Prerequisites -----------------------------------------------------------
#
# Everything this script consumes is read and validated before anything is deleted. The emitted
# files are committed sources, so a prerequisite discovered after the delete loop would leave the
# test source set missing files that cannot be rebuilt without the very input that was absent.

CORPUS_FILE = File.expand_path('../sep-51-corpus/corpus.json', __dir__)
CORPUS_OUTPUT = File.join(output_dir, 'Sep51CorpusData.kt')

unless File.exist?(CORPUS_FILE)
  abort <<~MESSAGE
    ERROR: #{CORPUS_FILE} is missing.
    Generate it with: python3 tools/sep-51-corpus/generate_corpus.py
  MESSAGE
end

corpus =
  begin
    JSON.parse(File.read(CORPUS_FILE))
  rescue JSON::ParserError => e
    abort <<~MESSAGE
      ERROR: #{CORPUS_FILE} is not valid JSON: #{e.message}
      Regenerate it with: python3 tools/sep-51-corpus/generate_corpus.py
    MESSAGE
  end

metadata = corpus.fetch('metadata') do
  abort "ERROR: #{CORPUS_FILE} has no \"metadata\" key. Regenerate it with: " \
        'python3 tools/sep-51-corpus/generate_corpus.py'
end
entries = corpus.fetch('entries') do
  abort "ERROR: #{CORPUS_FILE} has no \"entries\" key. Regenerate it with: " \
        'python3 tools/sep-51-corpus/generate_corpus.py'
end

# Emitted files are removed first so a type dropped upstream cannot leave a stale test behind.
Dir.glob(File.join(output_dir, '*.kt')).each do |file|
  File.delete(file) if File.read(file).start_with?('// Automatically generated by xdrgen')
end

Xdrgen::Compilation.new(
  filtered_files,
  output_dir: output_dir,
  generator: Xdrgen::Generators::KotlinJsonTests,
  namespace: 'com.soneso.stellar.sdk.xdr',
  options: {}
).compile

# --- SEP-0051 conformance corpus ---------------------------------------------
#
# commonTest has no filesystem API on the JavaScript and Apple targets, so the corpus is
# embedded as Kotlin source rather than read at test time. The emitted file is byte-determined
# by corpus.json alone; regenerate that first with tools/sep-51-corpus/generate_corpus.py.
# The file itself was read and validated above, before anything was deleted.

# Kotlin string literal body: backslash, quote and dollar carry meaning inside one, and
# anything outside the printable ASCII range is written as an escape so the emitted source
# is pure ASCII whatever the corpus holds.
def kotlin_string(value)
  escaped = +''
  value.each_char do |character|
    case character
    when '\\' then escaped << '\\\\'
    when '"' then escaped << '\\"'
    when '$' then escaped << '\\$'
    when "\n" then escaped << '\\n'
    when "\r" then escaped << '\\r'
    when "\t" then escaped << '\\t'
    else
      code = character.ord
      if code >= 0x20 && code <= 0x7E
        escaped << character
      elsif code <= 0xFFFF
        escaped << format('\\u%04X', code)
      else
        offset = code - 0x10000
        escaped << format('\\u%04X\\u%04X', 0xD800 + (offset >> 10), 0xDC00 + (offset & 0x3FF))
      end
    end
  end
  "\"#{escaped}\""
end

def kotlin_string_list(name, values)
  lines = ["internal val #{name}: List<String> = listOf("]
  values.each { |value| lines << "  #{kotlin_string(value)}," }
  lines << ')'
  lines.join("\n")
end

corpus_lines = []
corpus_lines << '// Automatically generated by xdrgen'
corpus_lines << '// DO NOT EDIT or your changes may be overwritten'
corpus_lines << ''
corpus_lines << 'package com.soneso.stellar.sdk.unitTests.xdr.json'
corpus_lines << ''
corpus_lines << '/**'
corpus_lines << ' * One SEP-0051 (XDR-JSON) conformance case: the exact JSON text the SDK must emit for'
corpus_lines << ' * [xdr], and the base64 XDR that value encodes to.'
corpus_lines << ' *'
corpus_lines << " * [source] is \"reference\" when SEP-0051's reference implementation emits the same text,"
corpus_lines << ' * and "incomparable" when SEP-0051 specifies a form that implementation does not emit.'
corpus_lines << ' */'
corpus_lines << 'internal data class Sep51CorpusEntry('
corpus_lines << '  val type: String,'
corpus_lines << '  val kmpType: String,'
corpus_lines << '  val xdr: String,'
corpus_lines << '  val json: String,'
corpus_lines << '  val source: String'
corpus_lines << ')'
corpus_lines << ''
corpus_lines << "/** SEP-0051 conformance cases for the XDR definitions pinned at #{metadata.fetch('sdk_xdr_commit')}. */"
corpus_lines << 'internal val SEP51_CORPUS: List<Sep51CorpusEntry> = listOf('
entries.each do |entry|
  corpus_lines << '  Sep51CorpusEntry('
  corpus_lines << "    #{kotlin_string(entry.fetch('type'))},"
  corpus_lines << "    #{kotlin_string(entry.fetch('kmp_type'))},"
  corpus_lines << "    #{kotlin_string(entry.fetch('xdr'))},"
  corpus_lines << "    #{kotlin_string(entry.fetch('json'))},"
  corpus_lines << "    #{kotlin_string(entry.fetch('oracle'))}"
  corpus_lines << '  ),'
end
corpus_lines << ')'
corpus_lines << ''
corpus_lines << '/** Enum members the reference could not resolve when the name table was last built. */'
corpus_lines << kotlin_string_list('SEP51_UNRESOLVABLE_ENUM_MEMBERS',
                                   metadata.fetch('unresolvable_enum_members'))
corpus_lines << ''
corpus_lines << '/** Struct types the reference could not resolve when the name table was last built. */'
corpus_lines << kotlin_string_list('SEP51_UNRESOLVABLE_STRUCT_TYPES',
                                   metadata.fetch('unresolvable_struct_types'))
corpus_lines << ''

File.write(CORPUS_OUTPUT, corpus_lines.join("\n"))

emitted = Dir.glob(File.join(output_dir, '*.kt')).sort
puts ''
puts "Emitted #{emitted.length} XDR-JSON test files in #{output_dir}:"
emitted.each { |file| puts "  - #{File.basename(file)}" }
puts ''
puts "Embedded #{entries.length} SEP-0051 corpus entries in #{File.basename(CORPUS_OUTPUT)}."
