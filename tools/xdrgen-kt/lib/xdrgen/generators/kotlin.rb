# frozen_string_literal: true

require_relative 'kotlin_json_names'
require_relative 'kotlin_json_overrides'

module Xdrgen
  module Generators
    # Kotlin code generator for XDR definitions
    # Generates idiomatic Kotlin code with proper type mappings:
    # - enum -> enum class
    # - struct -> data class
    # - union -> sealed hierarchy
    # - arrays -> List<T> or ByteArray
    # - strings -> String
    # - opaque -> ByteArray
    class Kotlin < Base
      # Structs that contain a variable-length array of themselves (directly recursive).
      # Their generated decode method wraps each recursive element with depth-guard calls.
      RECURSIVE_TYPES = %w[SorobanDelegateSignatureXdr].freeze
      XDR_RECURSION_CAP = 128

      # XDR string positions that carry arbitrary bytes rather than text: the CAP-85
      # executable tag, which the ledger matches byte for byte. Each entry maps an XDR
      # type name from the .x source to the string fields (struct) or arms (union) at
      # that type that are emitted as ByteArray, bypassing the string wrapper type, so
      # content that is not valid UTF-8 survives a decode/encode round trip exactly.
      # Only the named positions change; every other use of the same string typedef
      # keeps the generic emission.
      BYTES_BACKED_STRING_FIELDS = {
        'ContractExecutableExternalRef' => %w[tag].freeze,
        'SCVal' => %w[executable_tag].freeze
      }.freeze

      JSON_NAMES = KotlinJsonNames
      JSON_OVERRIDES = KotlinJsonOverrides

      JSON_ELEMENT_IMPORT = 'kotlinx.serialization.json.JsonElement'
      JSON_OBJECT_IMPORT = 'kotlinx.serialization.json.JsonObject'
      JSON_BUILDER_IMPORT = 'kotlinx.serialization.json.buildJsonObject'

      # Every generated file names its own type once, in a file-private constant, and the
      # XDR-JSON methods refer to that constant wherever the name would otherwise be repeated
      # at each call site.
      JSON_TYPE_CONSTANT = 'XDR_JSON_TYPE'

      # A struct names the keys it accepts once, beside its type name, so the decoder can reject
      # a key that belongs to no field without rebuilding the list at every call.
      JSON_KEYS_CONSTANT = 'XDR_JSON_KEYS'

      # A field named "type" is spelled "type_" by tooling that escapes it as a keyword of its
      # own language. SEP-0051 requires the key "type", so that is what this SDK emits; the
      # older spelling is accepted on input and never written back out.
      JSON_KEY_ALIASES = { 'type' => 'type_' }.freeze

      def generate
        @output_files = {}
        @package = @namespace.gsub('::', '.')
        @json_overrides_used = []
        @bytes_backed_string_fields_used = []

        # Skip XdrReader/XdrWriter generation - will be provided by KMP SDK
        # render_xdr_utils

        # Generate primitive type extensions
        render_primitive_extensions

        # Generate all type definitions
        render_definitions(@top)

        verify_json_overrides_consumed
        verify_bytes_backed_string_fields_consumed
      end

      private

      def render_definitions(node)
        node.definitions.each { |defn| render_definition(defn) }
        node.namespaces.each { |ns| render_definitions(ns) }
      end

      def render_nested_definitions(defn)
        return unless defn.respond_to?(:nested_definitions)
        defn.nested_definitions.each { |nested| render_definition(nested) }
      end

      def render_definition(defn)
        render_nested_definitions(defn)

        case defn
        when AST::Definitions::Struct
          render_struct(defn)
        when AST::Definitions::Enum
          render_enum(defn)
        when AST::Definitions::Union
          render_union(defn)
        when AST::Definitions::Typedef
          render_typedef(defn)
        when AST::Definitions::Const
          render_const(defn)
        end
      end

      def render_const(const)
        # Render constants as top-level const vals
        file_name = 'Constants.kt'

        # Initialize constants file if not exists
        unless @output_files&.key?(file_name)
          @output_files ||= {}
          out = @output.open(file_name)
          out.puts "// Automatically generated by xdrgen"
          out.puts "// DO NOT EDIT or your changes may be overwritten"
          out.puts
          out.puts "package #{@package}"
          out.puts
          @output_files[file_name] = out
        end

        out = @output_files[file_name]
        out.puts "const val #{const.name}: Int = #{const.value}"
      end

      def render_enum(enum)
        enum_name = name(enum)
        file_name = "#{enum_name}.kt"
        out = @output.open(file_name)

        render_file_header(out, [JSON_ELEMENT_IMPORT], enum_name)
        render_source_comment(out, enum)

        identifiers = enum.members.map(&:name)

        out.puts "enum class #{enum_name}(val value: Int, internal val xdrJsonName: String) {"
        out.indent do
          enum.members.each_with_index do |member, idx|
            # Extract and render comments for this member
            comments = extract_member_comment(enum.text_value, member.name)
            render_member_comment(out, comments)

            suffix = idx < enum.members.length - 1 ? ',' : ';'
            json_name = JSON_NAMES.enum_member_json_name(member.name, identifiers)
            out.puts "#{member.name}(#{member.value}, \"#{json_name}\")#{suffix}"
          end

          out.puts
          out.puts "companion object {"
          out.indent do
            out.puts ""
            out.puts "fun decode(reader: XdrReader): #{enum_name} {"
            out.indent do
              out.puts "val value = reader.readInt()"
              out.puts "return entries.find { it.value == value }"
              out.indent do
                out.puts "?: throw IllegalArgumentException(\"Unknown #{enum_name} value: \$value\")"
              end
            end
            out.puts "}"

            out.puts
            render_json_entry_points(out, enum_name)
            out.puts "internal fun fromXdrJsonTree(element: JsonElement): #{enum_name} {"
            out.indent do
              out.puts "val name = XdrJson.name(element, #{JSON_TYPE_CONSTANT})"
              out.puts "return findXdrJsonName(name) ?: XdrJson.unknownMember(#{JSON_TYPE_CONSTANT}, name)"
            end
            out.puts "}"

            out.puts
            out.puts "internal fun findXdrJsonName(name: String): #{enum_name}? = entries.find { it.xdrJsonName == name }"
          end
          out.puts "}"

          out.puts
          out.puts "fun encode(writer: XdrWriter) {"
          out.indent do
            out.puts "writer.writeInt(value)"
          end
          out.puts "}"

          out.puts
          out.puts "fun toXdrJsonElement(): JsonElement = XdrJson.name(xdrJsonName)"
          out.puts
          out.puts "fun toXdrJson(): String = XdrJson.encodeToString(toXdrJsonElement())"
        end
        out.puts "}"

        out.close
      end

      def render_typedef(typedef)
        typedef_name = name(typedef)
        file_name = "#{typedef_name}.kt"
        out = @output.open(file_name)

        override = json_override(typedef_name)
        render_file_header(out, json_imports(override, [JSON_ELEMENT_IMPORT]), typedef_name)
        render_source_comment(out, typedef)

        # All typedefs become inline value classes (like Java wrappers but zero-cost)
        kotlin_type = kotlin_type_for(typedef.declaration)

        out.puts "@Suppress(\"EXPECT_ACTUAL_INCOMPATIBILITY\")"
        out.puts "@kotlin.jvm.JvmInline"
        out.puts "value class #{typedef_name}(val value: #{kotlin_type}) {"
        out.indent do
          out.puts "companion object {"
          out.indent do
            out.puts "fun decode(reader: XdrReader): #{typedef_name} {"
            out.indent do
              out.puts "val value = #{decode_expression(typedef.declaration, 'reader')}"
              out.puts "return #{typedef_name}(value)"
            end
            out.puts "}"

            out.puts
            render_json_entry_points(out, typedef_name)
            if override
              out.puts override[:from]
            else
              from = json_from_expression(typedef.declaration, 'element', 'value')
              out.puts "internal fun fromXdrJsonTree(element: JsonElement): #{typedef_name} = #{typedef_name}(#{from})"
            end
          end
          out.puts "}"

          out.puts
          out.puts "fun encode(writer: XdrWriter) {"
          out.indent do
            encode_statement(typedef.declaration, 'value', 'writer', out)
          end
          out.puts "}"

          out.puts
          if override
            out.puts override[:to]
          else
            out.puts "fun toXdrJsonElement(): JsonElement = #{json_to_expression(typedef.declaration, 'value')}"
          end
          out.puts
          out.puts "fun toXdrJson(): String = XdrJson.encodeToString(toXdrJsonElement())"
        end
        out.puts "}"

        out.close
      end

      def render_struct(struct)
        struct_name = name(struct)
        file_name = "#{struct_name}.kt"
        out = @output.open(file_name)

        override = json_override(struct_name)
        default_imports = override ? [JSON_ELEMENT_IMPORT] : [JSON_ELEMENT_IMPORT, JSON_BUILDER_IMPORT]
        render_file_header(out, json_imports(override, default_imports), struct_name)
        render_declared_json_keys(out, struct) unless override
        render_source_comment(out, struct)

        out.puts "data class #{struct_name}("
        out.indent do
          struct.members.each_with_index do |member, idx|
            # Extract and render comments for this field
            comments = extract_member_comment(struct.text_value, member.name)
            render_member_comment(out, comments)

            member_name = escape_kotlin_keyword(member.name.underscore.camelize(:lower))
            member_type = member_kotlin_type(struct, member)
            suffix = idx < struct.members.length - 1 ? ',' : ''
            out.puts "val #{member_name}: #{member_type}#{suffix}"
          end
        end
        out.puts ") {"
        out.indent do
          # Companion object with decode method
          out.puts "companion object {"
          out.indent do
            out.puts ""
            out.puts "fun decode(reader: XdrReader): #{struct_name} {"
            out.indent do
              struct.members.each do |member|
                local_name = escape_kotlin_keyword(member.name.underscore.camelize(:lower))
                out.puts "val #{local_name} = #{member_decode_expression(struct, member, 'reader', struct_name: struct_name)}"
              end

              param_list = struct.members.map { |m|
                escape_kotlin_keyword(m.name.underscore.camelize(:lower))
              }.join(', ')
              out.puts "return #{struct_name}(#{param_list})"
            end
            out.puts "}"

            out.puts
            render_json_entry_points(out, struct_name)
            if override
              out.puts override[:from]
            else
              render_struct_from_json(out, struct, struct_name)
            end
          end
          out.puts "}"

          # Encode method
          out.puts
          out.puts "fun encode(writer: XdrWriter) {"
          out.indent do
            struct.members.each do |member|
              member_name = escape_kotlin_keyword(member.name.underscore.camelize(:lower))
              member_encode_statement(struct, member, member_name, 'writer', out)
            end
          end
          out.puts "}"

          out.puts
          if override
            out.puts override[:to]
          else
            out.puts "fun toXdrJsonElement(): JsonElement = buildJsonObject {"
            out.indent do
              struct.members.each do |member|
                member_name = escape_kotlin_keyword(member.name.underscore.camelize(:lower))
                key = JSON_NAMES.struct_field_json_name(member.name)
                out.puts "put(\"#{key}\", #{member_json_to_expression(struct, member, member_name)})"
              end
            end
            out.puts "}"
          end
          out.puts
          out.puts "fun toXdrJson(): String = XdrJson.encodeToString(toXdrJsonElement())"
        end
        out.puts "}"

        out.close
      end

      # Reads the object one key at a time and constructs positionally, so the JSON key order
      # and the constructor order are both the .x declaration order by construction.
      def render_struct_from_json(out, struct, struct_name)
        out.puts "internal fun fromXdrJsonTree(element: JsonElement): #{struct_name} {"
        out.indent do
          out.puts "val json = XdrJson.obj(element, #{JSON_TYPE_CONSTANT}, #{JSON_KEYS_CONSTANT})"
          out.puts "return #{struct_name}("
          out.indent do
            struct.members.each_with_index do |member, idx|
              key = JSON_NAMES.struct_field_json_name(member.name)
              field = json_field_expression(key)
              suffix = idx < struct.members.length - 1 ? ',' : ''
              out.puts "#{member_json_from_expression(struct, member, field, key)}#{suffix}"
            end
          end
          out.puts ")"
        end
        out.puts "}"
      end

      def json_field_expression(key)
        alias_key = JSON_KEY_ALIASES[key]
        if alias_key
          "XdrJson.field(json, \"#{key}\", \"#{alias_key}\", #{JSON_TYPE_CONSTANT})"
        else
          "XdrJson.field(json, \"#{key}\", #{JSON_TYPE_CONSTANT})"
        end
      end

      # Every key a struct answers to: its declared field keys, plus the historical spelling of
      # any field that accepts one. Listing both spellings lets the decoder recognise either as
      # the field it names; a document supplying both at once is rejected where the field is
      # read, which is what knows the two are one field.
      def render_declared_json_keys(out, struct)
        keys = struct.members.flat_map do |member|
          key = JSON_NAMES.struct_field_json_name(member.name)
          [key, JSON_KEY_ALIASES[key]].compact
        end
        literals = keys.map { |key| "\"#{key}\"" }.join(', ')
        out.puts "private val #{JSON_KEYS_CONSTANT}: Array<String> = arrayOf(#{literals})"
        out.puts
      end

      def render_union(union)
        union_name = name(union)
        file_name = "#{union_name}.kt"
        out = @output.open(file_name)

        override = json_override(union_name)
        render_file_header(out, json_imports(override, union_json_imports(union, override)), union_name)
        render_source_comment(out, union)

        # Sealed class hierarchy for unions
        # union.discriminant is the full declaration (has .type), union.discriminant_type is the resolved type
        discriminant_type = kotlin_type_for(union.discriminant)
        out.puts "sealed class #{union_name} {"
        out.indent do
          out.puts "abstract val discriminant: #{discriminant_type}"
          out.puts

          # Generate a subclass for each arm
          union.arms.each do |arm|
            next if arm.void?

            # Extract and render comments for this arm
            comments = extract_union_arm_comment(union.text_value, arm)
            render_member_comment(out, comments)

            arm_class_name = arm.name.camelize
            arm_type = member_kotlin_type(union, arm)
            is_default = arm.is_a?(AST::Definitions::UnionDefaultArm)

            if is_default || arm.cases.length > 1
              # Default arms and multi-case arms both need discriminant as a
              # constructor parameter so the wire-read value survives a
              # decode/encode round trip. Hardcoding here would lose the
              # discriminant for any case beyond the first.
              out.puts "data class #{arm_class_name}("
              out.indent do
                out.puts "override val discriminant: #{discriminant_type},"
                out.puts "val value: #{arm_type}"
              end
              out.puts ") : #{union_name}()"
            else
              out.puts "data class #{arm_class_name}("
              out.indent do
                out.puts "val value: #{arm_type}"
              end
              out.puts ") : #{union_name}() {"
              out.indent do
                # Discriminant value
                discriminant_value = arm_discriminant_value(arm, union.discriminant)
                out.puts "override val discriminant: #{discriminant_type} = #{discriminant_value}"
              end
              out.puts "}"
            end
            out.puts
          end

          # Void arms - handle arms with multiple discriminant values
          void_arms_by_class = union.arms.select(&:void?).group_by { |arm| arm.name.camelize }
          void_arms_by_class.each do |arm_class_name, arms|
            # For void arms, if an arm has multiple cases, we need a data class that accepts discriminant
            # Otherwise, we can use a data object with a fixed discriminant

            # Count total discriminant values across all arms with this class name
            total_discriminants = arms.sum { |arm| arm.cases.length }

            # Extract and render comments for the first arm (they're grouped by name)
            comments = extract_union_arm_comment(union.text_value, arms.first)
            render_member_comment(out, comments)

            is_default = arms.first.is_a?(AST::Definitions::UnionDefaultArm)

            if is_default || total_discriminants > 1
              # Default arms and multi-case void arms both need discriminant
              # as a constructor parameter — the wire-read value must survive
              # decode/encode.
              out.puts "data class #{arm_class_name}("
              out.indent do
                out.puts "override val discriminant: #{discriminant_type}"
              end
              out.puts ") : #{union_name}()"
            else
              # Single discriminant value - use data object with fixed discriminant
              discriminant_value = format_discriminant_value(arms.first.cases.first, union)
              out.puts "data object #{arm_class_name} : #{union_name}() {"
              out.indent do
                out.puts "override val discriminant: #{discriminant_type} = #{discriminant_value}"
              end
              out.puts "}"
            end
            out.puts
          end

          # Companion object with decode
          out.puts "companion object {"
          out.indent do
            out.puts ""
            out.puts "fun decode(reader: XdrReader): #{union_name} {"
            out.indent do
              out.puts "val discriminant = #{decode_expression(union.discriminant, 'reader')}"
              out.puts "return when (discriminant) {"
              out.indent do
                # Build a map to detect void arms with multiple discriminants.
                # `union.normal_arms` excludes the default arm — that case is
                # rendered separately below in the `union.default_arm.present?`
                # block. The class-definition predicate at the top of this method
                # uses `is_default || ...`; the predicate here intentionally does
                # not need the `is_default` check because the default arm never
                # reaches this loop.
                void_arms_by_class = {}
                union.normal_arms.select(&:void?).each do |arm|
                  class_name = arm.name.camelize
                  void_arms_by_class[class_name] ||= []
                  void_arms_by_class[class_name] << arm
                end

                union.normal_arms.each do |arm|
                  arm_class_name = arm.name.camelize

                  # For void arms, check if this class has multiple discriminants
                  has_multiple_discriminants = if arm.void?
                    arm_list = void_arms_by_class[arm_class_name]
                    # Count total cases across all arms with this name
                    total_cases = arm_list.sum { |a| a.cases.length }
                    total_cases > 1
                  else
                    false
                  end

                  arm.cases.each do |c|
                    discriminant_value = format_discriminant_value(c, union)

                    if arm.void?
                      if has_multiple_discriminants
                        # Multiple discriminants for same class - need to pass discriminant
                        out.puts "#{discriminant_value} -> #{arm_class_name}(discriminant)"
                      else
                        # Single discriminant - use data object
                        out.puts "#{discriminant_value} -> #{arm_class_name}"
                      end
                    else
                      out.puts "#{discriminant_value} -> {"
                      out.indent do
                        out.puts "val value = #{member_decode_expression(union, arm, 'reader')}"
                        if arm.cases.length > 1
                          out.puts "#{arm_class_name}(discriminant, value)"
                        else
                          out.puts "#{arm_class_name}(value)"
                        end
                      end
                      out.puts "}"
                    end
                  end
                end

                # Handle default arm if present
                if union.default_arm.present?
                  arm = union.default_arm
                  arm_class_name = arm.name.camelize
                  out.puts "else -> {"
                  out.indent do
                    if arm.void?
                      out.puts "#{arm_class_name}(discriminant)"
                    else
                      out.puts "val value = #{member_decode_expression(union, arm, 'reader')}"
                      out.puts "#{arm_class_name}(discriminant, value)"
                    end
                  end
                  out.puts "}"
                else
                  out.puts "else -> throw IllegalArgumentException(\"Unknown #{union_name} discriminant: \$discriminant\")"
                end
              end
              out.puts "}"
            end
            out.puts "}"

            out.puts
            render_json_entry_points(out, union_name)
            if override
              out.puts override[:from]
            else
              render_union_from_json(out, union, union_name)
            end
          end
          out.puts "}"

          # Encode method
          out.puts
          out.puts "fun encode(writer: XdrWriter) {"
          out.indent do
            encode_statement(union.discriminant, 'discriminant', 'writer', out)
            out.puts "when (this) {"
            out.indent do
              # Group arms by class name to avoid duplicate 'is' checks
              arms_by_class = union.arms.group_by { |arm| arm.name.camelize }
              arms_by_class.each do |class_name, _|
                arm = union.arms.find { |a| a.name.camelize == class_name }
                if arm.void?
                  out.puts "is #{class_name} -> {}"
                else
                  out.puts "is #{class_name} -> {"
                  out.indent do
                    member_encode_statement(union, arm, 'value', 'writer', out)
                  end
                  out.puts "}"
                end
              end
            end
            out.puts "}"
          end
          out.puts "}"

          out.puts
          if override
            out.puts override[:to]
          else
            render_union_to_json(out, union)
          end
          out.puts
          out.puts "fun toXdrJson(): String = XdrJson.encodeToString(toXdrJsonElement())"
        end
        out.puts "}"

        out.close
      end

      # A void arm is a bare string naming the arm; an arm carrying a value is an object with
      # that one key. An arm class covering more than one case, or the default arm, reads its
      # key from the discriminant it carries rather than from a name fixed here.
      def render_union_to_json(out, union)
        out.puts "fun toXdrJsonElement(): JsonElement = when (this) {"
        out.indent do
          union_json_classes(union).each do |entry|
            key = entry[:dynamic] ? union_json_dynamic_key(union) : "\"#{entry[:key]}\""
            if entry[:void]
              out.puts "is #{entry[:name]} -> XdrJson.name(#{key})"
            else
              arm = union.arms.find { |a| a.name.camelize == entry[:name] }
              value = member_json_to_expression(union, arm, 'value')
              out.puts "is #{entry[:name]} -> buildJsonObject { put(#{key}, #{value}) }"
            end
          end
        end
        out.puts "}"
      end

      def render_union_from_json(out, union, union_name)
        default = union_default_arm(union)
        value_arms = union.normal_arms.reject(&:void?)
        void_arms = union.normal_arms.select(&:void?)
        value_branch = value_arms.any? || (default && !default.void?)
        void_branch = void_arms.any? || (default && default.void?)
        both = value_branch && void_branch

        out.puts "internal fun fromXdrJsonTree(element: JsonElement): #{union_name} {"
        out.indent do
          if value_branch
            out.puts "if (element is JsonObject) {" if both
            out.indent(both ? 1 : 0) do
              out.puts "val (arm, value) = XdrJson.singleKeyObject(element, #{JSON_TYPE_CONSTANT})"
              out.puts "return when (arm) {"
              out.indent do
                value_arms.each do |arm|
                  arm.cases.each { |kase| out.puts union_json_case(union, arm, kase) }
                end
                out.puts union_json_default(union, default, union_name, value: true)
              end
              out.puts "}"
            end
            out.puts "}" if both
          end

          if void_branch
            out.puts "return when (val arm = XdrJson.name(element, #{JSON_TYPE_CONSTANT})) {"
            out.indent do
              void_arms.each do |arm|
                arm.cases.each { |kase| out.puts union_json_case(union, arm, kase) }
              end
              out.puts union_json_default(union, default, union_name, value: false)
            end
            out.puts "}"
          end
        end
        out.puts "}"
      end

      def union_default_arm(union)
        union.default_arm.present? ? union.default_arm : nil
      end

      def union_json_case(union, arm, kase)
        key = JSON_NAMES.union_arm_json_key(kase, union)
        class_name = arm.name.camelize
        discriminant = format_discriminant_value(kase, union)
        arguments = []
        arguments << discriminant if union_json_dynamic_arm?(union, arm)
        arguments << member_json_from_expression(union, arm, 'value', key) unless arm.void?

        if arguments.empty?
          "\"#{key}\" -> #{class_name}"
        else
          "\"#{key}\" -> #{class_name}(#{arguments.join(', ')})"
        end
      end

      # Without a default arm an unrecognised key is an error. With one, the key still has to
      # name a discriminant the union can carry: an enum member outside the explicit cases, or
      # the "v<n>" spelling of an integer discriminant.
      def union_json_default(union, default, union_name, value:)
        return "else -> XdrJson.unknownArm(#{JSON_TYPE_CONSTANT}, arm)" if default.nil?
        return "else -> XdrJson.unknownArm(#{JSON_TYPE_CONSTANT}, arm)" if default.void? != !value

        class_name = default.name.camelize
        arguments = [union_json_discriminant_from_key(union, union_name)]
        arguments << member_json_from_expression(union, default, 'value', 'default') unless default.void?
        "else -> #{class_name}(#{arguments.join(', ')})"
      end

      def union_json_discriminant_from_key(union, union_name)
        if union.discriminant_type.is_a?(AST::Definitions::Enum)
          enum_name = name(union.discriminant_type)
          "#{enum_name}.findXdrJsonName(arm) ?: XdrJson.unknownArm(#{JSON_TYPE_CONSTANT}, arm)"
        else
          require_int_discriminant(union, union_name)
          "XdrJson.intArm(#{JSON_TYPE_CONSTANT}, arm)"
        end
      end

      # The key an arm class derives from the discriminant it carries at run time.
      def union_json_dynamic_key(union)
        return 'discriminant.xdrJsonName' if union.discriminant_type.is_a?(AST::Definitions::Enum)

        require_int_discriminant(union, name(union))
        '"v$discriminant"'
      end

      def require_int_discriminant(union, union_name)
        return if kotlin_type_for(union.discriminant) == 'Int'

        raise "#{union_name} switches on #{kotlin_type_for(union.discriminant)}; SEP-0051 keys the " \
              'arms of an integer-discriminated union from the case value, which this generator ' \
              'only derives for a plain Int discriminant'
      end

      # Mirrors the arm-class shapes render_union emits: a class covering more than one case,
      # and the default arm, carry the discriminant so the wire-read value survives a round trip.
      def union_json_dynamic_arm?(union, arm)
        return true if arm.is_a?(AST::Definitions::UnionDefaultArm)
        return arm.cases.length > 1 unless arm.void?

        class_name = arm.name.camelize
        union.arms.select { |a| a.void? && a.name.camelize == class_name }
             .sum { |a| a.is_a?(AST::Definitions::UnionDefaultArm) ? 1 : a.cases.length } > 1
      end

      def union_json_classes(union)
        classes = {}
        union.arms.each do |arm|
          class_name = arm.name.camelize
          entry = (classes[class_name] ||= { name: class_name, void: arm.void?, dynamic: false, key: nil })
          entry[:dynamic] = true if union_json_dynamic_arm?(union, arm)
          next if arm.is_a?(AST::Definitions::UnionDefaultArm)

          entry[:key] ||= JSON_NAMES.union_arm_json_key(arm.cases.first, union)
        end
        classes.values
      end

      def union_json_imports(union, override)
        return [JSON_ELEMENT_IMPORT] if override

        imports = [JSON_ELEMENT_IMPORT]
        default = union_default_arm(union)
        if union.normal_arms.any? { |arm| !arm.void? } || (default && !default.void?)
          imports << JSON_BUILDER_IMPORT
          imports << JSON_OBJECT_IMPORT if union.normal_arms.any?(&:void?) || (default && default.void?)
        end
        imports
      end

      # Helper method to format a discriminant value for use in when expressions
      def format_discriminant_value(case_stmt, union)
        if case_stmt.value.is_a?(AST::Identifier)
          # For enum discriminants, get the enum type name
          discriminant_type_name = name(union.discriminant_type)
          "#{discriminant_type_name}.#{case_stmt.value.name}"
        else
          # Numeric literal - need to wrap in value class if discriminant is a typedef
          literal_value = case_stmt.value.value
          discriminant_type_name = kotlin_type_for(union.discriminant)

          if discriminant_type_name.end_with?('Xdr')
            # Wrap in value class constructor
            # Resolve to underlying type to determine literal suffix
            resolved_type = resolve_typedef_declaration(union.discriminant)
            wrapped_value = case resolved_type.type
            when AST::Typespecs::UnsignedInt
              "#{literal_value}u"
            when AST::Typespecs::UnsignedHyper
              "#{literal_value}uL"
            else
              literal_value.to_s
            end
            "#{discriminant_type_name}(#{wrapped_value})"
          else
            literal_value.to_s
          end
        end
      end

