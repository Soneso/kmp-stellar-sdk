      # The two public decode entry points. Both funnel into fromXdrJsonTree, which every
      # nested type calls directly: the depth limit is applied once, at the outermost type,
      # because applying it per nested value would rewalk the tree at every level.
      def render_json_entry_points(out, type_name)
        out.puts "fun fromXdrJson(json: String): #{type_name} = fromXdrJsonTree(XdrJson.parse(json, #{JSON_TYPE_CONSTANT}))"
        out.puts
        out.puts "fun fromXdrJsonElement(element: JsonElement): #{type_name} = " \
                 "fromXdrJsonTree(XdrJson.checkDepth(element, #{JSON_TYPE_CONSTANT}))"
        out.puts
      end

      def json_override(type_name)
        override = JSON_OVERRIDES.for_type(type_name)
        @json_overrides_used << type_name if override
        override
      end

      def json_imports(override, default_imports)
        return default_imports unless override

        default_imports + override[:imports]
      end

      # A registered override that never matched a generated type is a stale entry: the type
      # was renamed or removed, and the Stellar-specific rendering it carries has silently
      # stopped being applied. Only a run over the full Stellar .x set can conclude that, so
      # the caller opts in; a run over a subset says nothing about the registry.
      def verify_json_overrides_consumed
        return unless @options[:verify_json_overrides]

        missing = JSON_OVERRIDES.type_names - @json_overrides_used
        return if missing.empty?

        raise "SEP-0051 overrides registered for types this run did not generate: #{missing.join(', ')}"
      end

      # The same stale-entry rule for BYTES_BACKED_STRING_FIELDS: an entry that matched no
      # generated position names a renamed or removed field, and the ByteArray emission it
      # carries has silently stopped being applied. Opt-in for the same reason as
      # verify_json_overrides_consumed: only a run over the full Stellar .x set can conclude
      # an entry is stale.
      def verify_bytes_backed_string_fields_consumed
        return unless @options[:verify_bytes_backed_fields]

        registered = BYTES_BACKED_STRING_FIELDS.flat_map do |type, fields|
          fields.map { |field| "#{type}.#{field}" }
        end
        missing = registered - @bytes_backed_string_fields_used
        return if missing.empty?

        raise "Bytes-backed string fields registered for positions this run did not generate: #{missing.join(', ')}"
      end

      # Whether BYTES_BACKED_STRING_FIELDS names this struct field or union arm. A listed
      # position that is not an XDR string is a table mistake and raises rather than
      # emitting ByteArray code for a type the reader and writer calls do not fit.
      def bytes_backed_string_field?(defn, member)
        fields = BYTES_BACKED_STRING_FIELDS[defn.name]
        return false unless fields&.include?(member.name)

        resolved = resolve_typedef_declaration(member.declaration)
        unless resolved.type.is_a?(AST::Typespecs::String)
          raise "BYTES_BACKED_STRING_FIELDS names #{defn.name}.#{member.name}, which is not an XDR string"
        end

        (@bytes_backed_string_fields_used ||= []) << "#{defn.name}.#{member.name}"
        true
      end

      # The five positions a struct field or union arm is rendered at, each answering with
      # the ByteArray emission when BYTES_BACKED_STRING_FIELDS names the member and with
      # the generic one otherwise. The binary form of a string and of variable opaque is
      # identical (length prefix, bytes, padding), and the JSON form goes through the same
      # SEP-0051 escape ladder either way, so only the Kotlin representation differs.

      def member_kotlin_type(defn, member)
        return 'ByteArray' if bytes_backed_string_field?(defn, member)

        kotlin_type_for(member.declaration)
      end

      def member_decode_expression(defn, member, reader_var, struct_name: nil)
        return "#{reader_var}.readVariableOpaque()" if bytes_backed_string_field?(defn, member)
        return decode_expression(member.declaration, reader_var) if struct_name.nil?

        decode_expression_guarded(struct_name, member.declaration, reader_var)
      end

      def member_encode_statement(defn, member, value_expr, writer_var, out)
        if bytes_backed_string_field?(defn, member)
          out.puts "#{writer_var}.writeVariableOpaque(#{value_expr})"
        else
          encode_statement(member.declaration, value_expr, writer_var, out)
        end
      end

      def member_json_to_expression(defn, member, value_expr)
        return "XdrJson.escapedString(#{value_expr})" if bytes_backed_string_field?(defn, member)

        json_to_expression(member.declaration, value_expr)
      end

      def member_json_from_expression(defn, member, element_expr, key)
        unless bytes_backed_string_field?(defn, member)
          return json_from_expression(member.declaration, element_expr, key)
        end

        size = resolve_typedef_declaration(member.declaration).type.size
        "XdrJson.unescapeStringBytes(#{element_expr}, #{JSON_TYPE_CONSTANT}, \"#{key}\"#{json_max_length(size)})"
      end

      # The JSON form of a value, as an expression yielding a JsonElement.
      def json_to_expression(decl, value_expr)
        case decl
        when AST::Declarations::Optional
          "XdrJson.optional(#{value_expr}) { #{json_to_typespec(decl.type, 'it')} }"
        when AST::Declarations::Array
          values = decl.fixed? ? "#{value_expr}.asList()" : value_expr
          "XdrJson.array(#{values}) { #{json_to_typespec(decl.type, 'it')} }"
        else
          json_to_typespec(decl.type, value_expr)
        end
      end

      def json_to_typespec(typespec, value_expr)
        case typespec
        when AST::Typespecs::Int
          "XdrJson.int32(#{value_expr})"
        when AST::Typespecs::UnsignedInt
          "XdrJson.uint32(#{value_expr})"
        when AST::Typespecs::Hyper
          "XdrJson.int64(#{value_expr})"
        when AST::Typespecs::UnsignedHyper
          "XdrJson.uint64(#{value_expr})"
        when AST::Typespecs::Float, AST::Typespecs::Double, AST::Typespecs::Quadruple
          raise_unsupported_json_typespec(typespec)
        when AST::Typespecs::Bool
          "XdrJson.bool(#{value_expr})"
        when AST::Typespecs::String
          "XdrJson.escapedString(#{value_expr})"
        when AST::Typespecs::Opaque
          "XdrJson.hex(#{value_expr})"
        else
          "#{value_expr}.toXdrJsonElement()"
        end
      end

      # The Kotlin value read out of a JSON element, as an expression. Declared lengths and
      # maxima are checked here so a decoded instance is one the binary encoder also accepts.
      def json_from_expression(decl, element_expr, key)
        case decl
        when AST::Declarations::Optional
          inner = json_from_typespec(decl.type, 'it', key)
          "XdrJson.optional(#{element_expr})?.let { #{inner} }"
        when AST::Declarations::Array
          inner = json_from_typespec(decl.type, 'it', key)
          if decl.fixed?
            "XdrJson.array(#{element_expr}, #{JSON_TYPE_CONSTANT}, \"#{key}\", expectedLength = #{decl.size})" \
              ".map { #{inner} }.toTypedArray()"
          else
            "XdrJson.array(#{element_expr}, #{JSON_TYPE_CONSTANT}, \"#{key}\"#{json_max_length(decl.size)})" \
              ".map { #{inner} }"
          end
        else
          json_from_typespec(decl.type, element_expr, key)
        end
      end

      def json_from_typespec(typespec, element_expr, key)
        arguments = "#{element_expr}, #{JSON_TYPE_CONSTANT}, \"#{key}\""
        case typespec
        when AST::Typespecs::Int
          "XdrJson.int32(#{arguments})"
        when AST::Typespecs::UnsignedInt
          "XdrJson.uint32(#{arguments})"
        when AST::Typespecs::Hyper
          "XdrJson.int64(#{arguments})"
        when AST::Typespecs::UnsignedHyper
          "XdrJson.uint64(#{arguments})"
        when AST::Typespecs::Float, AST::Typespecs::Double, AST::Typespecs::Quadruple
          raise_unsupported_json_typespec(typespec)
        when AST::Typespecs::Bool
          "XdrJson.bool(#{arguments})"
        when AST::Typespecs::String
          "XdrJson.unescapeString(#{arguments}#{json_max_length(typespec.size)})"
        when AST::Typespecs::Opaque
          if typespec.fixed?
            "XdrJson.hex(#{arguments}, expectedLength = #{typespec.size})"
          else
            "XdrJson.hex(#{arguments}#{json_max_length(typespec.size)})"
          end
        when AST::Typespecs::Simple
          "#{name(typespec.resolved_type)}.fromXdrJsonTree(#{element_expr})"
        else
          "#{name(typespec)}.fromXdrJsonTree(#{element_expr})"
        end
      end

      def json_max_length(size)
        size.blank? ? '' : ", maxLength = #{size}"
      end

      def raise_unsupported_json_typespec(typespec)
        kind = typespec.class.name.split('::').last.downcase
        raise "SEP-0051 defines no JSON form for XDR #{kind}, which the Stellar .x files do not use"
      end

      def render_source_comment(out, defn)
        return if defn.is_a?(AST::Definitions::Namespace)

        out.puts "/**"
        out.puts " * XDR Source:"
        defn.text_value.each_line do |line|
          out.puts " * #{line.rstrip}"
        end
        out.puts " */"
      end

      # Extract comments for a specific member from the source text
      # Returns array of comment lines (without // prefix) that precede the member
      def extract_member_comment(source_text, member_name)
        lines = source_text.split("\n")
        comments = []

        lines.each_with_index do |line, idx|
          # Check if this line contains the member declaration
          if line =~ /^\s*\S+\s+#{Regexp.escape(member_name)}\s*[=,;]/ || line =~ /^\s*#{Regexp.escape(member_name)}\s*[=,;]/
            # Check for inline comment on the same line
            if line =~ /\/\/(.*)$/
              comments << $1.strip
            end

            # Look backwards for preceding comments
            i = idx - 1
            while i >= 0
              prev_line = lines[i].strip
              # Stop if we hit a non-comment, non-blank line
              break if !prev_line.empty? && !prev_line.start_with?('//')
              # Collect comment lines
              if prev_line.start_with?('//')
                comment_text = prev_line.sub(/^\/\/\s*/, '')
                comments.unshift(comment_text)
              end
              i -= 1
            end
            break
          end
        end

        comments
      end

      # Extract comments for a union arm from the source text
      # Union arms have format: case DISCRIMINANT_VALUE: // comment
      # Returns array of comment lines
      def extract_union_arm_comment(source_text, arm)
        comments = []

        # Try to get case values from the arm
        return [] unless arm.respond_to?(:cases)

        arm.cases.each do |case_stmt|
          # Get the case text which includes inline comments
          case_text = case_stmt.text_value rescue nil
          next unless case_text

          # Extract inline comment from case line
          if case_text =~ /\/\/(.*)$/
            comment_text = $1.strip
            comments << comment_text unless comment_text.empty?
          end
        end

        # If no inline comments, check for preceding comments
        if comments.empty? && arm.cases.first
          first_case = arm.cases.first
          lines = source_text.split("\n")

          # Find the case line
          lines.each_with_index do |line, idx|
            # Simple heuristic: match the start of the case text
            case_start = first_case.text_value.split("\n").first.strip rescue nil
            if case_start && line.include?(case_start)
              # Look backwards for comments
              i = idx - 1
              while i >= 0
                prev_line = lines[i].strip
                break if !prev_line.empty? && !prev_line.start_with?('//')
                if prev_line.start_with?('//')
                  comment_text = prev_line.sub(/^\/\/\s*/, '')
                  comments.unshift(comment_text)
                end
                i -= 1
              end
              break
            end
          end
        end

        comments
      end

      # Render KDoc comment for a member (enum value, struct field, etc.)
      def render_member_comment(out, comments)
        return if comments.empty?

        if comments.length == 1
          out.puts "/** #{comments.first} */"
        else
          out.puts "/**"
          comments.each { |line| out.puts " * #{line}" }
          out.puts " */"
        end
      end

      def kotlin_type_for(decl)
        case decl
        when AST::Declarations::Void
          'Unit'
        when AST::Declarations::Optional
          "#{kotlin_type_for_typespec(decl.type)}?"
        when AST::Declarations::Array
          if decl.fixed?
            # Fixed arrays could be Array<T> or ByteArray for bytes
            inner_type = kotlin_type_for_typespec(decl.type)
            inner_type == 'Byte' ? 'ByteArray' : "Array<#{inner_type}>"
          else
            # Variable arrays become List
            inner_type = kotlin_type_for_typespec(decl.type)
            inner_type == 'Byte' ? 'ByteArray' : "List<#{inner_type}>"
          end
        else
          kotlin_type_for_typespec(decl.type)
        end
      end

      def kotlin_type_for_typespec(typespec)
        case typespec
        when AST::Typespecs::Int
          'Int'
        when AST::Typespecs::UnsignedInt
          'UInt'
        when AST::Typespecs::Hyper
          'Long'
        when AST::Typespecs::UnsignedHyper
          'ULong'
        when AST::Typespecs::Float
          'Float'
        when AST::Typespecs::Double
          'Double'
        when AST::Typespecs::Quadruple
          raise "Quadruple not supported in Kotlin"
        when AST::Typespecs::Bool
          'Boolean'
        when AST::Typespecs::String
          'String'
        when AST::Typespecs::Opaque
          'ByteArray'
        when AST::Typespecs::Simple
          name(typespec.resolved_type)
        else
          name(typespec)
        end
      end

      # Like decode_expression but wraps variable-array element decodes with depth-guard
      # calls when the containing struct is in RECURSIVE_TYPES and the element type
      # resolves to the same struct (self-referential recursion).
      def decode_expression_guarded(struct_name, decl, reader_var)
        if RECURSIVE_TYPES.include?(struct_name) &&
           decl.is_a?(AST::Declarations::Array) &&
           !decl.fixed? &&
           kotlin_type_for_typespec(decl.type) == struct_name
          inner_decode = decode_expression_for_typespec(decl.type, reader_var)
          "List(#{reader_var}.readInt()) { " \
            "#{reader_var}.enterRecursion(#{XDR_RECURSION_CAP}); " \
            "try { #{inner_decode} } finally { #{reader_var}.exitRecursion() } }"
        else
          decode_expression(decl, reader_var)
        end
      end

      def decode_expression(decl, reader_var)
        case decl
        when AST::Declarations::Void
          # void
          ''
        when AST::Declarations::Optional
          inner_decode = decode_expression_for_typespec(decl.type, reader_var)
          "if (#{reader_var}.readBoolean()) #{inner_decode} else null"
        when AST::Declarations::Array
          if decl.fixed?
            _, size = decl.type.array_size
            inner_decode = decode_expression_for_typespec(decl.type, reader_var)

            if kotlin_type_for_typespec(decl.type) == 'Byte'
              "#{reader_var}.readFixedOpaque(#{size})"
            else
              "Array(#{size}) { #{inner_decode} }"
            end
          else
            inner_decode = decode_expression_for_typespec(decl.type, reader_var)

            if kotlin_type_for_typespec(decl.type) == 'Byte'
              "#{reader_var}.readVariableOpaque()"
            else
              "List(#{reader_var}.readInt()) { #{inner_decode} }"
            end
          end
        else
          decode_expression_for_typespec(decl.type, reader_var)
        end
      end

      def decode_expression_for_typespec(typespec, reader_var)
        case typespec
        when AST::Typespecs::Int
          "#{reader_var}.readInt()"
        when AST::Typespecs::UnsignedInt
          "#{reader_var}.readUnsignedInt()"
        when AST::Typespecs::Hyper
          "#{reader_var}.readLong()"
        when AST::Typespecs::UnsignedHyper
          "#{reader_var}.readUnsignedLong()"
        when AST::Typespecs::Float
          "#{reader_var}.readFloat()"
        when AST::Typespecs::Double
          "#{reader_var}.readDouble()"
        when AST::Typespecs::Bool
          "#{reader_var}.readBoolean()"
        when AST::Typespecs::String
          "#{reader_var}.readString()"
        when AST::Typespecs::Opaque
          if typespec.fixed?
            "#{reader_var}.readFixedOpaque(#{typespec.size})"
          else
            "#{reader_var}.readVariableOpaque()"
          end
        when AST::Typespecs::Simple
          type_name = name(typespec.resolved_type)
          "#{type_name}.decode(#{reader_var})"
        else
          type_name = name(typespec)
          "#{type_name}.decode(#{reader_var})"
        end
      end

      def encode_statement(decl, value_expr, writer_var, out)
        case decl
        when AST::Declarations::Void
          # Nothing to encode
        when AST::Declarations::Optional
          out.puts "if (#{value_expr} != null) {"
          out.indent do
            out.puts "#{writer_var}.writeBoolean(true)"
            encode_statement_for_typespec(decl.type, value_expr, writer_var, out)
          end
          out.puts "} else {"
          out.indent do
            out.puts "#{writer_var}.writeBoolean(false)"
          end
          out.puts "}"
        when AST::Declarations::Array
          if decl.fixed?
            if kotlin_type_for_typespec(decl.type) == 'Byte'
              _, size = decl.type.array_size
              out.puts "#{writer_var}.writeFixedOpaque(#{value_expr}, #{size})"
            else
              out.puts "#{value_expr}.forEach { item ->"
              out.indent do
                encode_statement_for_typespec(decl.type, 'item', writer_var, out)
              end
              out.puts "}"
            end
          else
            if kotlin_type_for_typespec(decl.type) == 'Byte'
              out.puts "#{writer_var}.writeVariableOpaque(#{value_expr})"
            else
              out.puts "#{writer_var}.writeInt(#{value_expr}.size)"
              out.puts "#{value_expr}.forEach { item ->"
              out.indent do
                encode_statement_for_typespec(decl.type, 'item', writer_var, out)
              end
              out.puts "}"
            end
          end
        else
          encode_statement_for_typespec(decl.type, value_expr, writer_var, out)
        end
      end

      def encode_statement_for_typespec(typespec, value_expr, writer_var, out)
        case typespec
        when AST::Typespecs::Int
          out.puts "#{writer_var}.writeInt(#{value_expr})"
        when AST::Typespecs::UnsignedInt
          out.puts "#{writer_var}.writeUnsignedInt(#{value_expr})"
        when AST::Typespecs::Hyper
          out.puts "#{writer_var}.writeLong(#{value_expr})"
        when AST::Typespecs::UnsignedHyper
          out.puts "#{writer_var}.writeUnsignedLong(#{value_expr})"
        when AST::Typespecs::Float
          out.puts "#{writer_var}.writeFloat(#{value_expr})"
        when AST::Typespecs::Double
          out.puts "#{writer_var}.writeDouble(#{value_expr})"
        when AST::Typespecs::Bool
          out.puts "#{writer_var}.writeBoolean(#{value_expr})"
        when AST::Typespecs::String
          out.puts "#{writer_var}.writeString(#{value_expr})"
        when AST::Typespecs::Opaque
          if typespec.fixed?
            out.puts "#{writer_var}.writeFixedOpaque(#{value_expr}, #{typespec.size})"
          else
            out.puts "#{writer_var}.writeVariableOpaque(#{value_expr})"
          end
        when AST::Typespecs::Simple
          out.puts "#{value_expr}.encode(#{writer_var})"
        else
          out.puts "#{value_expr}.encode(#{writer_var})"
        end
      end

      def arm_discriminant_value(arm, discriminant)
        # Handle default arm separately
        return 'else' if arm.is_a?(AST::Definitions::UnionDefaultArm)

        # Get the first case value for this arm
        first_case = arm.cases.first
        return 'else' unless first_case

        # Create a simple struct for union context
        # discriminant is already a declaration, .type gives us the typespec
        disc_type = discriminant.type.respond_to?(:resolved_type) ? discriminant.type.resolved_type : discriminant.type
        union_context = Struct.new(:discriminant, :discriminant_type).new(discriminant, disc_type)
        format_discriminant_value(first_case, union_context)
      end

      def simple_typedef?(decl)
        # Simple typedefs can use typealias
        case decl
        when AST::Declarations::Array, AST::Declarations::Optional
          false
        when AST::Declarations::Simple
          true
        else
          case decl.type
          when AST::Typespecs::Simple
            false # Reference types need wrappers
          else
            true # Primitive types can use typealias
          end
        end
      end

      def name(named)
        # Build the complete name path without Xdr suffixes, then add Xdr once at the end
        base_name = build_base_name(named)
        "#{base_name}Xdr"
      end

      def build_base_name(named)
        parent = build_base_name(named.parent_defn) if named.is_a?(AST::Concerns::NestedDefinition)
        result = named.name.camelize
        "#{parent}#{result}"
      end

      def escape_kotlin_keyword(name)
        # Kotlin keywords that need to be escaped with backticks
        kotlin_keywords = %w[val var fun class object interface when is in as break continue return this super if else while do for try catch finally throw typeof true false null]

        if kotlin_keywords.include?(name)
          "`#{name}`"
        else
          name
        end
      end

      def resolve_typedef_declaration(decl)
        # Resolve a declaration to its underlying type (following typedef chains)
        return decl unless decl.is_a?(AST::Declarations::Simple)

        # If it's a reference to another type, resolve it
        if decl.type.is_a?(AST::Typespecs::Simple)
          resolved_def = @top.find_definition(decl.type.text_value)
          if resolved_def.is_a?(AST::Definitions::Typedef)
            # Recursively resolve the typedef's declaration
            resolve_typedef_declaration(resolved_def.declaration)
          else
            decl
          end
        else
          decl
        end
      end

      def get_or_create_file(file_name)
        @output_files[file_name] ||= begin
          out = @output.open(file_name)
          out.puts "// Automatically generated by xdrgen"
          out.puts "// DO NOT EDIT or your changes may be overwritten"
          out.puts
          out.puts "package #{@package}"
          out.puts
          out
        end
      end
    end
